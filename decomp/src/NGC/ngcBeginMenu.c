/* 0x800b0274, size 0xb8 */
int BeginLoop(void)
{
{
    menu_init();
    ngcBeforeRender();
    PreDrawPad();
    ngcDoneRender();
    leStartLoadingEffect();
    lePrepareLoading();
    bg_init();
    leEndLoadingEffect();
    XBX_Input_GetInput();
    if (bPause) {
        g_bControllerTrc = 1;
    }
    while (g_bControllerTrc) {
        ngcBeforeRender();
        SetFont(10.0f, 36.0f, 1.0f);
        DRAW_TRC_CONTROLLER();
        XBX_Input_GetInput();
        if (just_button_up[0] & 0x1000) {
            ngcPlayMenuEffect(253);
            g_bControllerTrc = 0;
        }
        ngcDoneRender();
    }
    menu_loop();
    menu_free();
    menu_ingame_free();
    return 0;
}
}

/* 0x800b032c, size 0x4c */
void appNumClamp(int *start, int end, int increase)
{
{
    if (increase) {
        (*start)++;
        if (*start > end) {
            *start = 1;
        }
    } else {
        (*start)--;
        if (*start < 1) {
            *start = end;
        }
    }
}
}

