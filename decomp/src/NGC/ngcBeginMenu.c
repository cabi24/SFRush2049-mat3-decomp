/* 0x800afd5c, size 0x360 */
void XBX_Input_GetInput(void)
{
    static PADStatus MyPads[4];
    static PADStatus PreMyPads[4];

    PADRead(MyPads);
    PADClamp(MyPads);
    if (MyPads[0].err == -1) {
        bPause = 1;
        PADReset(0x80000000);
    } else {
        bPause = 0;
    }
    just_button_press[0] = MyPads[0].button;
    just_button_up[0] = (unsigned short)(PreMyPads[0].button & (PreMyPads[0].button ^ MyPads[0].button));
    just_button_down[0] = (unsigned short)(MyPads[0].button & (PreMyPads[0].button ^ MyPads[0].button));
    stick_up_press = MyPads[0].stickY > 60 ? 1 : 0;
    stick_down_press = MyPads[0].stickY < -60 ? 1 : 0;
    stick_left_press = MyPads[0].stickX > 60 ? 1 : 0;
    stick_right_press = MyPads[0].stickX < -60 ? 1 : 0;
    stick_up = PreMyPads[0].stickY > 60 ? 0 : MyPads[0].stickY > 60;
    stick_down = PreMyPads[0].stickY < -60 ? 0 : MyPads[0].stickY < -60;
    stick_left = PreMyPads[0].stickX > 60 ? 0 : MyPads[0].stickX > 60;
    stick_right = PreMyPads[0].stickX < -60 ? 0 : MyPads[0].stickX < -60;
    substick_up_press = MyPads[0].substickY > 50 ? 1 : 0;
    substick_down_press = MyPads[0].substickY < -50 ? 1 : 0;
    substick_left_press = MyPads[0].substickX > 50 ? 1 : 0;
    substick_right_press = MyPads[0].substickX < -50 ? 1 : 0;
    substick_up = PreMyPads[0].substickY > 50 ? 0 : MyPads[0].substickY > 50;
    substick_down = PreMyPads[0].substickY < -50 ? 0 : MyPads[0].substickY < -50;
    substick_left = PreMyPads[0].substickX > 50 ? 0 : MyPads[0].substickX > 50;
    substick_right = PreMyPads[0].substickX < -50 ? 0 : MyPads[0].substickX < -50;
    PreMyPads[0].button = MyPads[0].button;
    PreMyPads[0].stickY = MyPads[0].stickY;
    PreMyPads[0].stickX = MyPads[0].stickX;
    PreMyPads[0].substickY = MyPads[0].substickY;
    PreMyPads[0].substickX = MyPads[0].substickX;
}

