/* 0x800b05c0, size 0x284 */
void menu_loop(void)
{
{
    IniMenuOption();
    for (;;) {
        ngcBeforeRender();
        XBX_Input_GetInput();
        appCheckSlot();
        if (!DRAW_TRC_DVD()) {
            if (g_bShowGalleray) {
                ngcBlackBackground();
                _ProcessGalleryImage();
                _DrawGalleryImage();
            } else if (g_bShowBonus) {
                DrawAnimation(1);
                _ProcessBonusMenu();
                _DrawBonusMenu();
            } else {
                if (!bMenu && ((just_button_up[0] & 0x1000) || (just_button_up[0] & 0x100))) {
                    bVib = lastVib;
                    bAlt = lastPad;
                    bAuto = lastAuto;
                    bLoad = lastLoad;
                    return;
                }
                if ((just_button_up[0] & 0x400) || ((just_button_up[0] & 0x200) && bMenu && !bSubMenu)) {
                    ngcPlayMenuEffect(254);
                    numMenu = 1;
                    bSubMenu = 0;
                    bMenu = !bMenu;
                } else if (((just_button_up[0] & 0x100) || (just_button_up[0] & 0x200)) && bSubMenu) {
                    if (s_bMCSaveSucceeded) {
                        bSubMenu = 0;
                        numSubMenu = 1;
                        s_bMCSaveSucceeded = 0;
                    }
                    if (s_bMCResetSucceeded) {
                        bSubMenu = 0;
                        numSubMenu = 3;
                        s_bMCResetSucceeded = 0;
                    }
                    if (just_button_up[0] & 0x100) {
                        ngcPlayMenuEffect(253);
                        lastVib = curVib;
                        lastPad = curPad;
                        lastAuto = curAuto;
                        DoLoadSaveReset();
                    }
                    if (just_button_up[0] & 0x200) {
                        ngcPlayMenuEffect(252);
                        curVib = lastVib;
                        curPad = lastPad;
                        curAuto = lastAuto;
                    }
                    if (!s_bMCSaveSucceeded) {
                        bSubMenu = 0;
                        numSubMenu = 1;
                    }
                    if (s_bMCResetSucceeded) {
                        bSubMenu = 1;
                        numSubMenu = 3;
                    }
                } else if (just_button_up[0] & 0x100) {
                    s_bMCLoadSucceeded = 0;
                    ngcPlayMenuEffect(253);
                    DoLoadSaveReset();
                    bSubMenu = 1;
                    if (numMenu == 3 && !s_bMCLoadSucceeded) {
                        bSubMenu = 0;
                    }
                }
                DrawAnimation(1);
                if (bMenu) {
                    DrawMenu();
                    if (bSubMenu) {
                        DrawSubMenu();
                    }
                } else {
                    DrawPad();
                }
            }
        }
        UpdateOption();
        XBX_BufferSwap2();
        ngcDoneRender();
        ResetCheck();
    }
}
}

