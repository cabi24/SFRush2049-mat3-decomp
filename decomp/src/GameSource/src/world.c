/* 0x8005dd58, size 0x218 */
static void NewWorldObject(anon_name_mat_68 *Wnode, signed short Parent)
{
    signed short dlindex; /* r27 */
    int mbobj; /* r0 */
    anon_name_mat_68 *ptr; /* r26 */
    signed short cur_dlindex; /* r30 */

    cur_dlindex = -1;
    for (ptr = Wnode; ptr; ptr = ptr->next >= 0 ? WorldBase + ptr->next : 0) {
        if (g_bIfReload) {
            _Disenable_swap();
        } else {
            _Enable_swap();
        }
        _swap_x32_array((unsigned char *)&ptr->mat, 0x30);
        _swap_x32(&ptr->dlflags);
        _swap_x16(&ptr->next);
        _swap_x16(&ptr->child);
        _swap_x16(&ptr->sfx1);
        _swap_x16(&ptr->sfx2);
        _swap_x32(&ptr->tidx);
        _swap_x32(&ptr->min[0]);
        _swap_x32(&ptr->min[1]);
        _swap_x32(&ptr->min[2]);
        _swap_x32(&ptr->max[0]);
        _swap_x32(&ptr->max[1]);
        _swap_x32(&ptr->max[2]);
        cur_world_obj = ptr;
        if (!SetupTarget(ptr, Parent, 0, 1, -1, 1, 0)) {
            mbobj = MBOX_FindObject_WORK(ptr->name, 0, gNumModels - 1, 1);
            if (gGameState & 0x8) {
                dlindex = MBOX_NewObjectCam(mbobj, &ptr->mat, 1, Parent, ptr->dlflags);
            } else {
                dlindex = MBOX_NewObject(mbobj, &ptr->mat, Parent, ptr->dlflags);
            }
            if ((ptr->min[0] != ptr->max[0] || ptr->min[1] != ptr->max[1]) && Parent == -1) {
                ZOID_BuildCullingList(ptr->min, ptr->max, dlindex);
            }
            if (Worlddlidx == -1) {
                Worlddlidx = dlindex;
            }
            if (cur_dlindex == -1) {
                cur_dlindex = dlindex;
            }
        }
    }
    while (Wnode) {
        if (Wnode->child >= 0) {
            NewWorldObject(WorldBase + Wnode->child, cur_dlindex);
        }
        cur_dlindex++;
        if (Wnode->next >= 0) {
            Wnode = WorldBase + Wnode->next;
        } else {
            Wnode = 0;
        }
    }
}

