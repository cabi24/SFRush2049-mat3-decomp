            break;
        case 8:
            ptr = dm3Parts[best];
            break;
        case 9:
            ptr = dm4Parts[best];
            break;
        case 10:
            ptr = dm5Parts[best];
            break;
        case 11:
            ptr = dm6Parts[best];
            break;
        case 12:
