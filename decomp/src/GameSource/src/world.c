/* 0x8005e0fc, size 0x1f8 */
static void WorldDistance(anon_name_mat_68 *Wnode, float *pos, int *best, float *dist, int *widx, int *index)
{
    float dx;
    float dy;
    float dz;
    float d;

    for (;;) {
        dx = pos[0] - Wnode->mat.uvs[3][0];
        dy = pos[1] - Wnode->mat.uvs[3][1];
        dz = pos[2] - Wnode->mat.uvs[3][2];

        if (Wnode->min[0] <= dx && dx <= Wnode->max[0] && Wnode->min[1] <= dy && Wnode->min[2] <= dz &&
            dz <= Wnode->max[2]) {
            d = sqrtf(dx * dx + dz * dz);
            if (dy > 0.75f * Wnode->max[1]) {
                d += dy - Wnode->min[1];
            }
            if (*best < 0 || d < *dist) {
                *best = *index;
                *widx = Wnode - WorldBase;
                *dist = d;
            }
        }
        if (Wnode->next < 0) {
            break;
        }
        (*index)++;
        Wnode = WorldBase + Wnode->next;
    }
}

